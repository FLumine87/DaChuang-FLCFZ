"""临床词典：口语表述 → 规范症状/诱因名，以及危机信号扫描。

存在的原因（实测证据，2026-11-08）：

  · 领域 KG 的 Symptom 词表是规范名（失眠/疲惫/心慌/注意力不集中…）；
  · 而用户实际写进图谱的是口语名——
    实测全库真实数据：入睡困难、心悸、疲乏、疲劳、注意力难以集中、社交回避、自卑；
  · 两边靠 `MERGE {name}` 同名直接连通，名字不同就**连不上**。
    实测 12 个领域症状，xiaoyu 只命中 1 个（失眠），匹配率雪崩。

所以这里补一张别名表，在**读取侧**把口语名归一成规范名后再做匹配。
选择读取侧归一而不是写入侧改写，是因为：

  1. 历史数据已经以口语名落库，改写入侧救不了已有数据；
  2. 节点是全局 MERGE 的（同名同节点、跨用户共享），改写名字会动到别人的边；
  3. 词典可以随时增补，不需要重灌图谱。

映射原则：**宁可少映射，不做错映射**。语义不确定的一律不映射，
宁可让这条事实不参与匹配（漏检），也不能把它算到不相干的障碍上（误判）。
"""

from __future__ import annotations

# ---------- 危机信号 ----------

# 规范危机节点名：图谱里统一用这个名字承载"自杀/自伤意念"这类安全信号。
# 统一命名的意义在于——推理侧只需认一个名字，不必穷举用户可能的各种说法。
CRISIS_CANONICAL = "自杀意念"

# 原始文本直检用的模式（写入侧用，见 scan_crisis）。
# 覆盖实测漏检的说法：真实 LLM 会把"活着没意思"抽成"无意义感"，
# 这个词不含任何危机关键词，推理侧永远检不出来；所以在文本入口就拦住。
CRISIS_PATTERNS: tuple[str, ...] = (
    "自杀", "自伤", "自残", "轻生", "想死", "不想活", "活不下去",
    "活着没意思", "活着没意义", "活着没劲", "不如死", "结束生命",
    "结束自己", "了结自己", "跳楼", "割腕", "安眠药", "一了百了",
    "消失算了", "不存在就好了", "解脱", "遗书",
)

# 推理侧读取图谱节点名时的匹配关键词（比 CRISIS_PATTERNS 更宽，
# 因为节点名可能是"自杀意念""自伤念头"这类带后缀的形态）。
CRISIS_KEYWORDS: tuple[str, ...] = CRISIS_PATTERNS + (
    "自杀意念", "自杀倾向", "自伤念头", "绝望", "无意义感", "无价值感",
)


def scan_crisis(text: str) -> list[str]:
    """在**原始文本**里直检危机信号，返回命中的模式（去重、保持出现顺序）。

    为什么要有这一层：抽三元组是"语义归一"过程，LLM 可能把
    "活着没意思" 归一成 "无意义感"、"想消失" 归一成 "回避社交"——
    归一后的名字里已经没有危机关键词了，下游的 CRISIS_KEYWORDS 匹配必然漏检。
    安全相关不能只依赖一次可能失真的语义转换，所以文本入口再直检一次。
    """
    if not text:
        return []
    seen: list[str] = []
    for kw in CRISIS_PATTERNS:
        if kw in text and kw not in seen:
            seen.append(kw)
    return seen


