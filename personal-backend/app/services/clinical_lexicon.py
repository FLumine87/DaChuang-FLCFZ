def _normalize(name: str, table: dict[str, tuple[str, ...]]) -> tuple[str, ...]:
    """归一单个名称；表里没有就原样返回（规范名自身天然命中）。"""
    if not name:
        return ()
    key = name.strip()
    if not key:
        return ()
    return table.get(key, (key,))


def normalize_symptoms(name: str) -> tuple[str, ...]:
    """把症状名归一成领域规范名。可能返回多个（一对多别名）。"""
    return _normalize(name, SYMPTOM_ALIASES)


def normalize_triggers(name: str) -> tuple[str, ...]:
    """把诱因/事件名归一成领域规范诱因名。事件与诱因共用一张表。"""
    return _normalize(name, TRIGGER_ALIASES)
